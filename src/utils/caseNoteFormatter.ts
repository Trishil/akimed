import { PatientProfile, DiagnosticAssessment, AkinatorState } from '../types/clinical';

export function formatSoapNote(
  patient: PatientProfile,
  assessment?: DiagnosticAssessment | null,
  akinatorState?: AkinatorState | null
): string {
  const topD = assessment?.topDiagnoses?.[0] || akinatorState?.finalDiagnosis || akinatorState?.differentialRanking?.[0];
  const triage = assessment?.triage;

  const vitalsText = patient.vitalSigns
    ? `BP: ${patient.vitalSigns.bpSystolic || '?'}/${patient.vitalSigns.bpDiastolic || '?'} mmHg | HR: ${patient.vitalSigns.heartRate || '?'} bpm | RR: ${patient.vitalSigns.respiratoryRate || '?'} /min | SpO2: ${patient.vitalSigns.spo2 || '?'}% | Temp: ${patient.vitalSigns.temperatureC || '?'} °C`
    : 'Not recorded';

  let lines: string[] = [
    '======================================================================',
    '       AKIMED CLINICAL CASE SUMMARY (MBBS SOAP / SBAR FORMAT)         ',
    '======================================================================',
    '',
    '[S] SUBJECTIVE:',
    `• Patient: ${patient.age}-year-old ${patient.gender}${patient.isPregnant ? ' (PREGNANT)' : ''}`,
    `• Chief Complaint(s): "${patient.chiefSymptoms}" (Duration: ${patient.symptomDuration || 'Unspecified'})`,
    `• History of Present Illness / Notes: ${patient.additionalNotes || 'None recorded'}`,
    `• Travel Epidemiology: ${patient.travelHistory || 'No recent international travel'}`,
    `• Past Medical History: ${patient.preExistingConditions && patient.preExistingConditions.length > 0 ? patient.preExistingConditions.join(', ') : 'None reported'}`,
    `• Current Medications: ${patient.currentMedications && patient.currentMedications.length > 0 ? patient.currentMedications.join(', ') : 'None'}`,
    `• Allergies: ${patient.allergies && patient.allergies.length > 0 ? patient.allergies.join(', ') : 'No Known Drug Allergies (NKDA)'}`,
    '',
    '[O] OBJECTIVE:',
    `• Vital Signs: ${vitalsText}`,
    `• Bedside Signs to Elicit: ${topD?.bedsideSignsToTest ? topD.bedsideSignsToTest.join(' • ') : 'Standard system examination'}`,
    '',
    '[A] ASSESSMENT & TRIAGE:',
    `• ESI Triage Level: ${triage ? `Level ${triage.level} (${triage.levelName}) — Target Time to MD: ${triage.timeToPhysician}` : 'Awaiting bedside triage'}`,
    `• Triage Rationale: ${triage?.rationale || 'Evaluated based on clinical presentation and vitals'}`,
    `• Red Flags: ${triage?.redFlags && triage.redFlags.length > 0 ? triage.redFlags.join('; ') : 'No acute hemodynamic compromise flags detected'}`,
    '',
    '• DIFFERENTIAL DIAGNOSIS SPECTRUM:',
  ];

  const diffList = assessment?.topDiagnoses || akinatorState?.differentialRanking || (topD ? [topD] : []);
  diffList.slice(0, 5).forEach((d, idx) => {
    lines.push(`  ${idx + 1}. ${d.diseaseName} (${d.likelihood}% posterior likelihood) [${d.category || 'Differential'}]`);
    if (d.icd10Code) lines.push(`     ICD-10: ${d.icd10Code}`);
    lines.push(`     Mechanism: ${d.pathophysiology}`);
    if (d.supportingFindings && d.supportingFindings.length > 0) {
      lines.push(`     Corroborating Findings: ${d.supportingFindings.slice(0, 3).join('; ')}`);
    }
    if (d.recommendedWorkup?.confirmatoryTests && d.recommendedWorkup.confirmatoryTests.length > 0) {
      lines.push(`     Confirmatory Tests: ${d.recommendedWorkup.confirmatoryTests.join(', ')}`);
    }
  });

  if (assessment?.allergyAndMedicationAlerts && assessment.allergyAndMedicationAlerts.length > 0) {
    lines.push('');
    lines.push('• PHARMACOLOGICAL & ALLERGY GUARDRAILS:');
    assessment.allergyAndMedicationAlerts.forEach((alert) => {
      lines.push(`  [!ALERT] ${alert.substance} (${alert.warningType} - ${alert.severity}): ${alert.details}`);
    });
  }

  lines.push('');
  lines.push('[P] CLINICAL ACTION PLAN:');
  if (assessment?.immediateActionPlan && assessment.immediateActionPlan.length > 0) {
    assessment.immediateActionPlan.forEach((step, idx) => {
      lines.push(`  ${idx + 1}. ${step}`);
    });
  } else {
    lines.push(`  1. Prioritize immediate ABCDE primary survey and stabilization.`);
    lines.push(`  2. Order confirmatory workup for leading differential: ${topD?.diseaseName || 'Primary candidate'}.`);
    lines.push(`  3. Establish continuous monitoring and senior physician bedside consultation.`);
  }

  lines.push('');
  lines.push('======================================================================');
  lines.push(`Generated by AkiMed Clinical Diagnostic Engine • ${new Date().toLocaleString()}`);
  lines.push('======================================================================');

  return lines.join('\n');
}
